pub fn label(code: &str) -> Option<&'static str> {
    ALL.iter()
        .find(|(id, _)| *id == code)
        .map(|(_, label)| *label)
}
pub fn code(name: &str) -> Option<&'static str> {
    ALL.iter()
        .find(|(id, label)| id.eq_ignore_ascii_case(name) || label.eq_ignore_ascii_case(name))
        .map(|(id, _)| *id)
}
pub fn speech_supported(code: &str) -> bool {
    // The pinned multilingual small model predates the Cantonese token added
    // in large-v3. Cantonese remains available as a text translation target.
    label(code).is_some() && code != "yue"
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn catalog_is_unique_and_matches_the_pinned_model() {
        let unique: std::collections::HashSet<_> = ALL.iter().map(|(code, _)| code).collect();
        assert_eq!(unique.len(), 100);
        assert_eq!(
            ALL.iter()
                .filter(|(code, _)| speech_supported(code))
                .count(),
            99
        );
        assert_eq!(code("Spanish"), Some("es"));
        assert!(!speech_supported("yue"));
        assert!(!speech_supported("qu"));
    }
}
